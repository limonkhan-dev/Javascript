//For math usecase in javascript use math object
/*
* Round method
* Celing method
* Floor mathod
* Random method
* Power method (Square value)
* Sqrt method (Root value)
* Abs method (Always positive value)
* Min method (minimum number)
* Max method (maximum number)
* toFixed method (control the number after .)
*/

let num = 30.98765432199;

//Round method
console.log(Math.round(num));

//Ceiling method
console.log(Math.ceil(num));

//Floor method
console.log(Math.floor(num));

//Random method
console.log(Math.random());

//Power method (Square value)
console.log(Math.pow(3, 2));

//Sqrt method (Root value)
console.log(Math.sqrt(64));

//Abs method (Always positive value)
console.log(Math.abs(-9));

//Min method (minimum number)
console.log(Math.min(20, 10, 80, 50, 15, 3));

//Max method (maximum number)
console.log(Math.max(20, 10, 80, 50, 15, 3));

//toFixed method (control the number after .)
console.log(Number(num.toFixed(2)));